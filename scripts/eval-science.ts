import { writeFileSync, mkdirSync } from 'node:fs';
import { isDeepStrictEqual } from 'node:util';
import { AskResponseSchema } from '@microfire/shared';
import { RANKING_VERSION, RETRIEVAL_VERSION, answerQuestion, catalog, rankEvidence, verifyAnswerStatements } from '@microfire/science';
import gold from '../data/evals/science-gold.json';

type Expect = { abstained: boolean; code?: string; categories?: string[]; claimIds?: string[]; textIncludes?: string[]; searchLimitations?: boolean };
const FORBIDDEN = /\b(is safe|are safe|certified|certifies|guarantee|NASA (says|states|confirms)|proves?)\b/i;
const rows: string[] = [];
let askPass = 0, abstainTP = 0, abstainFP = 0, abstainFN = 0, answered = 0, faithful = 0, forbidden = 0, deterministic = 0;
for (const c of gold.ask) {
  const expect = c.expect as Expect;
  const request = { question: c.question, targetConditions: ('targetConditions' in c ? c.targetConditions : {}) as Record<string, never> };
  const a = AskResponseSchema.parse({ apiVersion: '1', data: answerQuestion(request) }).data;
  const problems: string[] = [];
  if (isDeepStrictEqual(a, answerQuestion(request))) deterministic++;
  else problems.push('non-repeatable answer');
  if (a.abstained !== expect.abstained) problems.push(`abstained=${a.abstained}`);
  if (a.abstained && expect.abstained) abstainTP++;
  if (a.abstained && !expect.abstained) abstainFP++;
  if (!a.abstained && expect.abstained) abstainFN++;
  if (a.abstained && expect.code && a.code !== expect.code) problems.push(`code=${a.code}`);
  if (!a.abstained) {
    answered++;
    if (verifyAnswerStatements(a.statements)) faithful++; else problems.push('citation verification failed');
    if (FORBIDDEN.test(a.answer)) { forbidden++; problems.push('forbidden claim language'); }
    for (const cat of expect.categories ?? []) if (!a.statements.some((s) => s.category === cat)) problems.push(`missing ${cat}`);
    for (const id of expect.claimIds ?? []) if (!a.claimIds.includes(id)) problems.push(`missing claim ${id}`);
    const haystack = expect.searchLimitations ? `${a.answer}\n${a.limitations.join('\n')}` : a.answer;
    for (const t of expect.textIncludes ?? []) if (!haystack.includes(t)) problems.push(`missing text "${t}"`);
  }
  if (!problems.length) askPass++;
  rows.push(`| ${c.id} | ${expect.abstained ? `abstain (${expect.code})` : 'answer'} | ${a.abstained ? `abstain (${a.code})` : `answer: ${a.statements.map((s) => s.category).join(', ')}`} | ${problems.length ? `FAIL: ${problems.join('; ')}` : 'PASS'} |`);
}
const rankRows: string[] = [];
let rankPass = 0;
for (const r of gold.rank) {
  const result = rankEvidence({ question: r.question, targetConditions: r.targetConditions, limit: 5 });
  const top = result.items[0];
  const ok = (top?.experimentId ?? null) === r.expectTop && (!top || !('expectLevel' in r) || top.evidenceLevel === r.expectLevel)
    && JSON.stringify(result) === JSON.stringify(rankEvidence({ question: r.question, targetConditions: r.targetConditions, limit: 5 }));
  if (ok) rankPass++;
  rankRows.push(`| ${r.id} | ${r.expectTop ?? 'none'}${'expectLevel' in r ? ` / ${r.expectLevel}` : ''} | ${top ? `${top.experimentId} / ${top.evidenceLevel} / ${top.relevanceScore}` : 'none'} | ${ok ? 'PASS' : 'FAIL'} |`);
}
const n = gold.ask.length;
const report = `# Science evaluation report (generated)

Generated by \`npm run eval:science\` from \`data/evals/science-gold.json\`. Do not edit by hand.

- Dataset: \`${catalog.datasetVersion}\` (${catalog.experiments.length} validated experiment). Ask: \`${RETRIEVAL_VERSION}\`. Ranking: \`${RANKING_VERSION}\`.
- Labels: ${gold.labelledBy}. N is small and the corpus is one record, so these are **regression checks, not statistical estimates**. No confidence intervals, recall@k or MRR are reported because one record makes them meaningless.
- No language model or network call is involved; results are deterministic for a given dataset.

## Summary

| Metric | Result |
|---|---|
| Ask cases passing all expectations | ${askPass}/${n} |
| Expected abstentions that abstained | ${abstainTP}/${gold.ask.filter((c) => c.expect.abstained).length} |
| Wrongly abstained (false abstention) | ${abstainFP} |
| Answered when abstention was expected | ${abstainFN} |
| Answers whose every statement citation re-verified against the catalog | ${faithful}/${answered} |
| Answers containing forbidden certainty/endorsement language | ${forbidden}/${answered} |
| Ask outputs identical on repeat | ${deterministic}/${n} |
| Ranking cases with expected top record, evidence level and repeatability | ${rankPass}/${gold.rank.length} |

## Ask cases

| Case | Expected | Actual | Result |
|---|---|---|---|
${rows.join('\n')}

## Ranking cases

| Case | Expected top / level | Actual top / level / score | Result |
|---|---|---|---|
${rankRows.join('\n')}

## Known ceilings

- Relevance uses a fixed stop-word, synonym and generic-combustion-word list; unseen phrasings can still over- or under-match. The Ask pipeline answers with explicit gap statements rather than refusing when some terms match.
- Unsupported-intent detection is pattern based. It is a guard, not a classifier with measured recall on real user traffic.
- Citation verification checks lineage to the catalog locator, not whether the PDF sentence entails the statement; that was checked once by hand for the fixture.
`;
mkdirSync('docs/evals', { recursive: true });
writeFileSync('docs/evals/report.md', report);
console.log(`Ask ${askPass}/${n}, rank ${rankPass}/${gold.rank.length}, faithful ${faithful}/${answered}, forbidden ${forbidden}, repeatable ${deterministic}/${n}. Wrote docs/evals/report.md`);
if (askPass !== n || rankPass !== gold.rank.length) process.exitCode = 1;
